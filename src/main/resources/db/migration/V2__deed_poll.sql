-- deedpoll_deedpoll -- the case table, ported from the DeedPoll model in
-- src/test/resources/reference/deed-poll.prisma. Child tables follow in V3.
--
-- This is a PORT, not a redesign. Column names, types and nullability reproduce the
-- reference exactly, because the reference schema is a live store whose rows this service
-- will eventually take over, and the schema-conformance test compares the two field by
-- field. Consequences worth knowing before "tidying" any of it:
--
--   * Column names are mixed case and therefore quoted. Unquoted camelCase would fold to
--     lower case and stop matching the reference.
--   * "signaturerecieveddate" is misspelled. The misspelling is in the source Dynamics
--     column; the reference maps a corrected field name onto it (@map) and this column
--     keeps the source spelling deliberately. Do not correct it.
--   * "id" is text, not uuid, holding a UUID generated by the application rather than by
--     the database -- again matching the reference, so ids survive the data migration
--     unchanged.
--   * "modifiedOn" is NOT NULL with no default: the application always writes it (the
--     reference's @updatedAt). A raw INSERT that omits it will fail, which is intended.
--   * The three int[] multiselects are nullable with an empty-array default, which is what
--     the reference produces. They preserve the Dynamics option-set integers.

CREATE TABLE "deedpoll_deedpoll" (
    "id"                             text                            NOT NULL,

    -- Identity. "referencenumber" is the serial component; "displayReference" is the
    -- rendered "{prefix}{year}-{serial}" form, stored as a unique key for lookups.
    "referencenumber"                integer,
    "displayReference"               text,

    -- General / classification
    "type"                           "DeedPollType",
    "state"                          "DeedPollState",
    "privacy"                        "Privacy"                       NOT NULL DEFAULT 'Normal',
    "urgency"                        "Urgency"                       NOT NULL DEFAULT 'Normal',
    "urgencyreason"                  text,
    "postCounter"                    "PostCounter",
    "inPerson"                       boolean,
    "migratedRecord"                 boolean                         NOT NULL DEFAULT false,
    "retainPermanently"              boolean                         NOT NULL DEFAULT false,
    "maritalStatus"                  "MaritalStatus",
    "feeReference"                   text,
    "onlineApplicationReference"     text,

    -- Applicant name
    "newForename"                    varchar(1000),
    "newMiddleName"                  varchar(1000),
    "newSurname"                     varchar(1000),
    "oldForename"                    varchar(1000),
    "oldMiddleName"                  varchar(1000),
    "oldSurname"                     varchar(1000),

    -- Applicant address & contact (flat text -- no contact/account linkage)
    "applicantBuildingNoName"        text,
    "applicantEmail"                 text,
    "applicantTelephone"             text,
    "applicantAddress1"              text,
    "applicantAddress2"              text,
    "applicantTownCity"              text,
    "applicantPostcode"              text,

    -- Representative address & contact (flat text)
    "representativeName"             text,
    "representativeBuildingNoName"   text,
    "representativeCompany"          text,
    "representativeAddress1"         text,
    "representativeEmail"            text,
    "representativeAddress2"         text,
    "representativeTelephone"        text,
    "representativeTownCity"         text,
    "representativePostcode"         text,

    -- Minor
    "ageOfMinor"                     integer,
    "ageOfMinorMonths"               integer,
    "minorDateOfBirth"               timestamp(3),
    "parents"                        text,

    -- Public-journey fields. All nullable: they exist because the source Dynamics entity
    -- cannot store what a redesigned public-facing journey needs to capture, and the
    -- caseworker service is unaffected by them. The reference documents the specific gap
    -- each one closes.
    "placeOfBirth"                   varchar(100),
    "nationalitySubject"             varchar(20),
    "nationalitySectionProvenance"   varchar(30),
    "parentRelationship"             varchar(100),
    "parentAddress1"                 varchar(100),
    "parentAddress2"                 varchar(100),
    "parentTownCity"                 varchar(100),
    "parentPostcode"                 varchar(10),
    "parentCountry"                  varchar(100),
    "secondParentName"               varchar(1000),
    "secondParentRelationship"       varchar(100),

    -- Nationality
    "nationality"                    "Nationality",
    "nationalitySection"             "NationalitySection",
    "nationalitySectionOther"        text,

    -- Declarations. Multiselects stored as int[] preserving the Dynamics option values:
    --   iShall           1 wife, 2 husband, 3 civil partner, 4 children, 5 I alone
    --   iHaveSubscribed  1 forename, 2 middle, 3 surname
    --   andAlsoMyOld     1 forename, 2 middle, 3 surname
    "iShall"                         integer[]                       DEFAULT ARRAY[]::integer[],
    "iHaveSubscribed"                integer[]                       DEFAULT ARRAY[]::integer[],
    "andAlsoMyOld"                   integer[]                       DEFAULT ARRAY[]::integer[],
    "dateOfDeclaration"              timestamp(3),

    -- Dates driving state
    "dateOfApplication"              timestamp(3),
    "dateReceived"                   timestamp(3),
    "awaitingFurtherDocsInfo"        timestamp(3),
    "signatureRequestedDate"         timestamp(3),
    -- Source column misspelled "recieved". Kept as-is; the entity exposes the corrected
    -- name and maps to this column.
    "signaturerecieveddate"          timestamp(3),
    "dateReadyForMaster"             timestamp(3),
    "dateReferred"                   timestamp(3),
    "dateEnroled"                    timestamp(3),
    "dateReturned"                   timestamp(3),
    "dateNoticeSentToLondonGazette"  timestamp(3),

    -- Master / referral
    "referToMasterChoice"            "ReferToMaster",
    "masterName"                     text,
    "masterDirections"               text,
    "masterDecision"                 "MasterDecision",
    "masterDateOfDecision"           timestamp(3),
    "dateDecisionDirectionsReceived" timestamp(3),
    "referralNotes"                  text,
    "publishToLondonGazette"         boolean                         NOT NULL DEFAULT true,

    -- Return / refund
    "returnReason"                   text,
    "refundAmount"                   numeric(12, 2),
    "dateOfRefund"                   timestamp(3),
    "refundReference"                text,

    -- Audit. "createdBy"/"modifiedBy" hold the display name resolved at write time, not a
    -- foreign key -- there is no user table, and the source case header shows the name as
    -- captured. Nullable, because rows predating the columns have no attributable author.
    "createdOn"                      timestamp(3)                    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "modifiedOn"                     timestamp(3)                    NOT NULL,
    "createdBy"                      varchar(200),
    "modifiedBy"                     varchar(200),

    CONSTRAINT "deedpoll_deedpoll_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX "deedpoll_deedpoll_displayReference_key" ON "deedpoll_deedpoll" ("displayReference");

CREATE INDEX "deedpoll_deedpoll_state_idx" ON "deedpoll_deedpoll" ("state");
CREATE INDEX "deedpoll_deedpoll_type_idx" ON "deedpoll_deedpoll" ("type");
CREATE INDEX "deedpoll_deedpoll_dateReceived_idx" ON "deedpoll_deedpoll" ("dateReceived");
